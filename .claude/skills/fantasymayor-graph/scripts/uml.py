"""PlantUML views of the game's boot drawn from the graph alone: one global flow (the state machine) and one global
structure (Boot, the machine, the states, the installer layers that fill them, the singletons one state leaves for
another), then a flow and a structure for every game state. Written into Assets/Diagrams/ on every build; a file
whose text did not change is left untouched."""
from __future__ import annotations

import re
from pathlib import Path

DIAGRAMS_DIR = "Assets/Diagrams"
STATES_SUBDIR = "states"
HEADER = "' generated by fantasymayor-graph (fmgraph.py build | uml) — every edit is overwritten"
LIVE_REQUESTS = ("Events.Raise", "Switch")   # the two ways a mode is actually asked for; assign is kept, never raised
ENTRY_MEMBER = "EnterAsync"                  # a request made here is made once the state's entry has run
KIND_INTERFACES = ("IPipelineStageSystem", "IUniTaskSystem", "IUpdatedSystem", "ILateUpdatedSystem")
EVENT_READS = ("consumes", "reacts_to", "polls")
SINGLETON_WRITE, SINGLETON_READS = "Singletons.Set", ("Singletons.Get", "Singletons.Has")
BROKEN = "#C62828"
# the header stands INSIDE @startuml: an IDE preview renders the diagram under the caret, and a file opens with the
# caret on line 1 — a comment above @startuml leaves the caret outside every diagram


def write_diagrams(root: Path, graph) -> list[Path]:
    """Render every diagram and write the ones whose text changed; a .puml no longer rendered is removed."""
    diagrams = render_diagrams(graph)
    for rel_path, text in diagrams.items():
        check_ide_previewable(rel_path, text)
    out_dir = root / DIAGRAMS_DIR
    (out_dir / STATES_SUBDIR).mkdir(parents=True, exist_ok=True)
    written = []
    for rel_path, text in diagrams.items():
        path = out_dir / rel_path
        if not path.exists() or path.read_text("utf-8") != text:
            path.write_text(text, "utf-8")
            written.append(path)
    rendered = {out_dir / rel_path for rel_path in diagrams}
    for stale in [*out_dir.glob("*.puml"), *(out_dir / STATES_SUBDIR).glob("*.puml")]:
        if stale not in rendered:
            stale.unlink()
    return written


def check_ide_previewable(rel_path: str, text: str):
    """A diagram an IDE can preview: line 1 is @startuml and nothing but a newline follows @enduml. Rider's
    plantuml4idea previews the diagram under the caret and opens a file with the caret on line 1 — a comment or a
    blank line above @startuml leaves the caret outside every diagram and the preview empty, while the command-line
    renderer still passes. Thrown before anything is written, so a bad diagram never reaches disk."""
    lines = text.split("\n")
    if lines[0] != "@startuml":
        raise ValueError(f"{rel_path}: line 1 is {lines[0]!r}, not @startuml — an IDE preview renders the diagram "
                         f"under the caret, and a file opens with the caret on line 1")
    body = text.rstrip("\n").split("\n")
    if body[-1] != "@enduml" or text.count("@startuml") != 1 or text.count("@enduml") != 1:
        raise ValueError(f"{rel_path}: one diagram per file, from @startuml on line 1 to @enduml on the last line")


def render_diagrams(graph) -> dict[str, str]:
    boot = BootFacts(graph)
    diagrams = {"flow.puml": render_global_flow(boot), "structure.puml": render_global_structure(boot)}
    for state in boot.states:
        diagrams[f"{STATES_SUBDIR}/{short(state)}.flow.puml"] = render_state_flow(boot, state)
        diagrams[f"{STATES_SUBDIR}/{short(state)}.structure.puml"] = render_state_structure(boot, state)
    return diagrams


class BootFacts:
    """What every diagram reads: the game states in the order the game reaches them, the systems each runs with
    their installer, kind, Priority and place in the registration order, every request for a mode, the event the
    switcher reads, and the singletons one state writes for another."""

    def __init__(self, graph):
        self.graph = graph
        self.requests = sorted((e for e in graph.edges if e["rel"] == "requests_state"),
                               key=lambda e: (e["src"], e["dst"], e["source_location"]))
        self.start = next((e for e in self.requests if e["via"] == "Switch"), None)
        self.switcher = self.start["src"] if self.start else None
        self.request_events = sorted(e["dst"] for e in graph.outgoing.get(self.switcher, [])
                                     if e["rel"] in EVENT_READS) if self.switcher else []
        self.registration_order = self.order_registrations()
        self.states = self.order_states(sorted(i for i, n in graph.nodes.items() if n.get("state")))
        self.systems = {state: self.systems_of(state) for state in self.states}
        self.live_reached = self.reach_live()
        self.singleton_links = self.link_singletons()

    def order_states(self, states: list[str]) -> list[str]:
        """The start state, then every state a request reaches, breadth first; the states nothing reaches last."""
        ordered = [self.start["dst"]] if self.start else []
        for current in ordered:
            for edge in self.requests_out_of(current):
                if edge["dst"] not in ordered:
                    ordered.append(edge["dst"])
        return ordered + [s for s in states if s not in ordered]

    def requests_out_of(self, state: str) -> list[dict]:
        """Requests the state makes itself, and requests made by the systems that run in it."""
        return [e for e in self.requests if e["via"] != "Switch" and e["src"] in self.members_of(state)]

    def members_of(self, state: str) -> set[str]:
        return {state} | {e["src"] for e in self.graph.incoming[state] if e["rel"] == "runs_in"}

    def reach_live(self) -> set[str]:
        reached = [self.start["dst"]] if self.start else []
        for current in reached:
            for edge in self.requests_out_of(current):
                if edge["via"] in LIVE_REQUESTS and edge["dst"] not in reached:
                    reached.append(edge["dst"])
        return set(reached)

    def entered_by_nobody(self, state: str) -> bool:
        return not any(e["dst"] == state for e in self.requests)

    def order_registrations(self) -> dict[str, int]:
        """Every registration's place in the order the container sees it: each root installer's body line by line,
        an installer handed the builder (new X().Install(builder)) expanded at the line of that call. Line order
        stands in for call order inside one installer — a helper method called earlier but declared later reads
        late."""
        graph = self.graph
        installers = [i for i, n in graph.nodes.items() if n.get("kind") == "installer"]
        installed = {e["dst"] for e in graph.edges if e["rel"] == "installs"}
        order = {}

        def expand(installer: str, trail: tuple):
            steps = [(e["source_location"], e) for e in graph.outgoing[installer] if e["rel"] in ("registers", "installs")]
            for _, edge in sorted(steps, key=lambda step: location_key(step[0])):
                if edge["rel"] == "registers":
                    order.setdefault(edge["source_location"], len(order))
                elif edge["dst"] not in trail:
                    expand(edge["dst"], trail + (edge["dst"],))

        for root in sorted(i for i in installers if i not in installed):
            expand(root, (root,))
        return order

    def systems_of(self, state: str) -> list[dict]:
        systems = []
        for edge in (e for e in self.graph.incoming[state] if e["rel"] == "runs_in"):
            node = self.graph.nodes[edge["src"]]
            installer = next((r["src"] for r in self.graph.incoming[edge["src"]]
                              if r["rel"] == "registers" and r["source_location"] == edge["source_location"]), "?")
            systems.append({"id": edge["src"], "label": edge["src"] + generic(edge.get("args", [])),
                            "installer": installer, "kinds": self.kinds_of(edge["src"]),
                            "priority": node.get("priority"), "role": node.get("role"),
                            "registered_at": edge["source_location"],
                            "order": self.registration_order.get(edge["source_location"], len(self.registration_order))})
        return sorted(systems, key=lambda s: (s["order"], s["label"]))

    def kinds_of(self, system: str) -> set[str]:
        """The kind interfaces the system reaches through its bases — AppStateSystems.Filter files it by them."""
        seen, frontier = set(), [system]
        while frontier:
            current = frontier.pop()
            for edge in self.graph.outgoing[current]:
                if edge["rel"] == "inherits" and edge["dst"] not in seen:
                    seen.add(edge["dst"])
                    frontier.append(edge["dst"])
        return seen & set(KIND_INTERFACES)

    def link_singletons(self) -> dict[tuple, list[str]]:
        """(writer state, reader state) → the singletons a member of the first sets and a member of the second
        reads. A singleton any code outside the states sets (an installer, Boot) is always there and draws no link."""
        state_of = {}
        for state in self.states:
            for member in self.members_of(state):
                state_of.setdefault(member, set()).add(state)
        writers, readers = {}, {}
        for edge in self.graph.edges:
            if edge["rel"] == "writes" and edge["via"] == SINGLETON_WRITE:
                writers.setdefault(edge["dst"], set()).add(edge["src"])
            elif edge["rel"] == "reads" and edge["via"] in SINGLETON_READS:
                readers.setdefault(edge["dst"], set()).add(edge["src"])
        links = {}
        for singleton, writing in writers.items():
            if any(w not in state_of for w in writing):
                continue
            writer_states = set().union(*(state_of[w] for w in writing))
            reader_states = set().union(*(state_of.get(r, set()) for r in readers.get(singleton, set())))
            for writer_state in writer_states:
                for reader_state in reader_states - writer_states:
                    links.setdefault((writer_state, reader_state), []).append(singleton)
        return {pair: sorted(names) for pair, names in sorted(links.items())}

    def singleton_broken(self, writer_state: str) -> bool:
        return writer_state != (self.start or {}).get("dst") and self.entered_by_nobody(writer_state)


# --- global flow ---------------------------------------------------------------------------------------------------

def render_global_flow(boot: BootFacts) -> str:
    lines = ["@startuml", HEADER, "title Game flow — app states", "hide empty description", ""]
    for state in boot.states:
        count = len(boot.systems[state])
        lines.append(f"state {short(state)}{state_color(boot, state)} : {count} system{'s' if count != 1 else ''}")
        if state not in boot.live_reached:
            lines.append(f"state {short(state)} : {unreached_reason(boot, state)}")
        elif not any(e["via"] in LIVE_REQUESTS for e in boot.requests_out_of(state)):
            lines.append(f"state {short(state)} : **no live way out**")
    lines.append("")
    if boot.start:
        lines.append(f"[*] --> {short(boot.start['dst'])} : {boot.start['src']} · Switch")
    for state in boot.states:
        for edge in boot.requests_out_of(state):
            lines.append(f"{short(state)} {arrow(edge)} {short(edge['dst'])} : {request_label(edge)}")
    if boot.switcher:
        first = short(boot.start["dst"])
        lines += ["", f"note right of {first}",
                  f"  **{boot.switcher}** switches the mode: it starts in {first}",
                  f"  and switches on every {' / '.join(boot.request_events) or 'request'} it reads.",
                  "  A mode kept in a field and never raised switches nothing.",
                  "end note"]
    for writer_state, reader_state in (pair for pair in boot.singleton_links if boot.singleton_broken(pair[0])):
        names = ", ".join(boot.singleton_links[(writer_state, reader_state)])
        lines += [f"note left of {short(reader_state)}",
                  f"  <color:{BROKEN}>reads {names},</color>",
                  f"  <color:{BROKEN}>written only in {short(writer_state)} — entered by nobody</color>",
                  "end note"]
    lines += ["", "legend right",
              f"solid — {' / '.join(boot.request_events) or 'a request'} raised, read by {boot.switcher or 'the switcher'}",
              "dashed — a mode assigned to a field, never raised",
              "grey — no live request leads here",
              "endlegend", "@enduml", ""]
    return "\n".join(lines)


def state_color(boot: BootFacts, state: str) -> str:
    return "" if state in boot.live_reached else " #lightgrey"


def unreached_reason(boot: BootFacts, state: str) -> str:
    return "entered by nobody" if boot.entered_by_nobody(state) else "only a dashed request leads here"


def arrow(edge: dict) -> str:
    return "-->" if edge["via"] in LIVE_REQUESTS else "-[dashed]->"


def request_label(edge: dict) -> str:
    how = "assigned, never raised" if edge["via"] == "assign" else edge["via"]
    when = "end of entry" if edge.get("member") == ENTRY_MEMBER else f"in {edge['member']}" if edge.get("member") else ""
    return " · ".join(part for part in (edge["src"], how, when) if part)


# --- global structure ----------------------------------------------------------------------------------------------

def render_global_structure(boot: BootFacts) -> str:
    graph = boot.graph
    lines = ["@startuml", HEADER, "title Game structure — boot, app states, installer layers", "left to right direction",
             "skinparam componentStyle rectangle", ""]
    machine = next((e["src"] for e in graph.edges if e["rel"] == "injects" and e["dst"] == "IAppState"
                    and e.get("collection")), None)
    if boot.switcher:
        lines.append(f"component {boot.switcher} as {alias('N', boot.switcher)}")
    if machine:
        lines.append(f"component {machine} as {alias('N', machine)}")
    lines += [f"queue {event} as {alias('E', event)}" for event in boot.request_events]
    lines.append('package "App states" {')
    for state in boot.states:
        count = len(boot.systems[state])
        lines.append(f'  component "{short(state)}\\n{count} system{"s" if count != 1 else ""}" as {alias("S", state)}'
                     f'{state_color(boot, state)}')
    lines.append("}")

    per_layer = {}
    for state in boot.states:
        for system in boot.systems[state]:
            layer = layer_of(graph, system["installer"])
            per_layer.setdefault(layer, {"installers": set(), "counts": {}})
            per_layer[layer]["installers"].add(system["installer"])
            per_layer[layer]["counts"][state] = per_layer[layer]["counts"].get(state, 0) + 1
    lines.append('package "Installer layers" {')
    for layer, facts in sorted(per_layer.items()):
        names = "\\n".join(short_installer(i) for i in sorted(facts["installers"]))
        lines.append(f'  component "**{layer}**\\n{names}" as {alias("L", layer)}')
    lines.append("}")
    lines.append("")

    if boot.switcher and machine and any(e["dst"] == machine for e in graph.outgoing[boot.switcher]
                                         if e["rel"] == "injects"):
        lines.append(f"{alias('N', boot.switcher)} --> {alias('N', machine)} : Switch · Tick")
    for event in boot.request_events:
        lines.append(f"{alias('E', event)} --> {alias('N', boot.switcher)} : reads")
    if machine:
        lines += [f"{alias('N', machine)} --> {alias('S', s)}" for s in boot.states]
    for state in boot.states:
        for edge in boot.requests_out_of(state):
            if edge["via"] == "Events.Raise":
                for event in boot.request_events:
                    lines.append(f"{alias('S', state)} --> {alias('E', event)} : {edge['src']} → {short(edge['dst'])}")
            else:
                lines.append(f"{alias('S', state)} -[dashed,{BROKEN}]-> {alias('S', edge['dst'])} : "
                             f"<color:{BROKEN}>{edge['src']} · assigned, never raised</color>")
    for layer, facts in sorted(per_layer.items()):
        for state, count in sorted(facts["counts"].items(), key=lambda item: boot.states.index(item[0])):
            lines.append(f"{alias('L', layer)} ..> {alias('S', state)} : {count}")
    for (writer_state, reader_state), names in boot.singleton_links.items():
        style = f"-[dashed,{BROKEN}]->" if boot.singleton_broken(writer_state) else "-[dotted]->"
        rows = names + ([f"never written — {short(writer_state)} is entered by nobody"]
                        if boot.singleton_broken(writer_state) else [])
        label = "\\n".join(f"<color:{BROKEN}>{row}</color>" if boot.singleton_broken(writer_state) else row
                            for row in rows)   # a creole colour never spans a line break
        lines.append(f"{alias('S', writer_state)} {style} {alias('S', reader_state)} : {label}")
    lines += ["", "legend right",
              "dotted number — systems an installer layer puts into a state",
              "dotted between states — singletons one state writes and another reads",
              "red — a broken link: a mode never raised, a singleton never written",
              "endlegend", "@enduml", ""]
    return "\n".join(lines)


def layer_of(graph, installer: str) -> str:
    parts = graph.nodes.get(installer, {}).get("source_location", "").split("/")
    return parts[1] if len(parts) > 2 and parts[0] == "Assets" else "Other"


def short_installer(installer: str) -> str:
    name = installer.rsplit(".", 1)[-1]
    return name[:-len("Installer")] if name.endswith("Installer") and len(name) > len("Installer") else name


# --- per-state flow ------------------------------------------------------------------------------------------------

def render_state_flow(boot: BootFacts, state: str) -> str:
    graph = boot.graph
    systems = boot.systems[state]
    entry_steps = [s for s in systems if "IUniTaskSystem" in s["kinds"] and "IPipelineStageSystem" not in s["kinds"]]
    stages = by_priority([s for s in systems if "IPipelineStageSystem" in s["kinds"]])
    ticked = by_priority([s for s in systems if "IUpdatedSystem" in s["kinds"]])
    late = by_priority([s for s in systems if "ILateUpdatedSystem" in s["kinds"]])
    entry_run = graph.nodes[state].get("entry_run")
    exits = boot.requests_out_of(state)
    entry_exits = [e for e in exits if e.get("member") == ENTRY_MEMBER]
    tick_exits = [e for e in exits if e.get("member") != ENTRY_MEMBER]

    lines = ["@startuml", HEADER, f"title {short(state)} — flow", "start", f":enter {short(state)};"]
    if state not in boot.live_reached:
        lines.append(f"note right: <color:{BROKEN}>**{unreached_reason(boot, state)}** — "
                     f"this flow never runs today</color>")
    if entry_steps and entry_run == "parallel":
        lines.append(activity("entry steps — all at once", [s["label"] for s in entry_steps]))
    elif entry_steps:
        lines.append('partition "entry steps — registration order" {')
        lines += [f"  :{text(s['label'])};" for s in entry_steps]
        lines.append("}")
    if stages and entry_run == "parallel":
        lines.append(f"note right: {len(stages)} pipeline stage(s) not run — RunAllAsync awaits entry steps only")
    elif stages:
        lines.append('partition "pipeline stages — by Priority" {')
        lines += [f"  :{text(s['label'])} · {s['priority']};" for s in stages]
        lines.append("}")
    if not entry_run and (entry_steps or stages):
        lines.append("note right: the state runs no entry — these systems never execute on enter")
    if entry_exits:
        lines.append(activity("at the end of entry, requests", [exit_line(e) for e in entry_exits]))

    lines.append(f"while (in {short(state)}?) is (each frame)")
    lines.append(activity("Tick — by Priority", [f"{s['label']} · {s['priority']}" for s in ticked]))
    lines.append(activity("LateTick — by Priority", [f"{s['label']} · {s['priority']}" for s in late]))
    if entry_exits and not tick_exits:
        lines.append(f"endwhile ({boot.switcher or 'the switcher'} reads the request)")
    else:
        lines.append("endwhile (a mode is requested)")

    if tick_exits:
        lines.append(activity("while ticking, requests", [exit_line(e) for e in tick_exits]))
    elif not exits:
        lines.append(":nothing requests another mode;")
    lines += ["stop", "@enduml", ""]
    return "\n".join(lines)


def exit_line(edge: dict) -> str:
    return f"{short(edge['dst'])} — {request_label(edge)}"


def activity(title: str, items: list[str]) -> str:
    body = "\\n".join(f"• {text(item)}" for item in items) if items else "—"
    return f":**{title}**\\n{body};"


def by_priority(systems: list[dict]) -> list[dict]:
    return sorted(systems, key=lambda s: (s["priority"] is None, s["priority"] or 0, s["label"]))


# --- per-state structure -------------------------------------------------------------------------------------------

def render_state_structure(boot: BootFacts, state: str) -> str:
    graph = boot.graph
    systems = boot.systems[state]
    lines = ["@startuml", HEADER, f"title {short(state)} — structure", "left to right direction",
             "skinparam componentStyle rectangle", "",
             f"component {state} as {alias('S', state)}{state_color(boot, state)}"]

    by_installer = {}
    for system in systems:
        by_installer.setdefault(system["installer"], []).append(system)
    for installer, members in sorted(by_installer.items()):
        lines.append(f'package "{installer}" {{')
        for system in members:
            details = " · ".join(str(d) for d in (system["role"], priority_text(system["priority"])) if d)
            label = text(system["label"]) + (f"\\n{details}" if details else "")
            lines.append(f'  component "{label}" as {alias("Y", system["label"])}')
        lines.append("}")

    inside = {state: alias("S", state)}
    for system in systems:
        inside.setdefault(system["id"], alias("Y", system["label"]))
    events, read_inside, links, outside = set(), set(), set(), set()
    for owner, owner_alias in inside.items():
        for edge in graph.outgoing[owner]:
            if edge["rel"] == "emits":
                events.add(edge["dst"])
                links.add(f"{owner_alias} --> {alias('E', edge['dst'])} : emits")
            elif edge["rel"] in EVENT_READS:
                events.add(edge["dst"])
                read_inside.add(edge["dst"])
                links.add(f"{alias('E', edge['dst'])} --> {owner_alias} : {edge['rel']}")
    for event in events:
        for edge in graph.incoming[event]:
            if edge["src"] in inside:
                continue
            if edge["rel"] == "emits" and event in read_inside:   # who from outside feeds what the state reads
                outside.add(edge["src"])
                links.add(f"{alias('X', edge['src'])} --> {alias('E', event)} : emits")
            elif edge["rel"] in EVENT_READS and edge["src"] == boot.switcher:
                outside.add(edge["src"])
                links.add(f"{alias('E', event)} --> {alias('X', edge['src'])} : {edge['rel']}")

    lines.append("")
    lines += [f"queue {event} as {alias('E', event)}" for event in sorted(events)]
    if outside:
        lines.append('package "outside this state" {')
        lines += [f"  component {name} as {alias('X', name)}" for name in sorted(outside)]
        lines.append("}")
    lines.append("")
    lines += sorted(links)

    inputs = [(writer, names) for (writer, reader), names in boot.singleton_links.items() if reader == state]
    outputs = [(reader, names) for (writer, reader), names in boot.singleton_links.items() if writer == state]
    if inputs or outputs:
        lines += ["", f"note bottom of {alias('S', state)}"]
        for writer, names in inputs:
            line = f"  reads {', '.join(names)} — written in {short(writer)}"
            lines.append(f"  <color:{BROKEN}>{line.strip()} (entered by nobody)</color>"
                         if boot.singleton_broken(writer) else line)
        for reader, names in outputs:
            line = f"writes {', '.join(names)} — read in {short(reader)}"
            lines.append(f"  <color:{BROKEN}>{line} — never, this state is entered by nobody</color>"
                         if boot.singleton_broken(state) else f"  {line}")
        lines.append("end note")
    lines += ["@enduml", ""]
    return "\n".join(lines)


def priority_text(priority) -> str:
    return f"Priority {priority}" if priority is not None else ""


# --- names ---------------------------------------------------------------------------------------------------------

def short(state: str) -> str:
    """A state's name without its namespace and the State suffix: MainMenuState → MainMenu."""
    name = state.rsplit(".", 1)[-1]
    return name[:-len("State")] if name.endswith("State") and len(name) > len("State") else name


def generic(args) -> str:
    return f"<{', '.join(args)}>" if args else ""


def alias(prefix: str, name: str) -> str:
    return f"{prefix}_{re.sub(r'[^0-9A-Za-z_]', '_', name)}"


def location_key(location: str) -> tuple:
    path, _, line = location.rpartition(":")
    return path, int(line) if line.isdigit() else 0


def text(label: str) -> str:
    """A label PlantUML reads as plain text: generic angle brackets would open a creole tag."""
    return label.replace("<", "‹").replace(">", "›")
